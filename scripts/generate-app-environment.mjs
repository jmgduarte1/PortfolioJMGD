import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';

const envFile = new URL('../.env', import.meta.url);
const defaults = parseEnv(readFileSync(new URL('../.env.example', import.meta.url), 'utf8'));
const local = existsSync(envFile) ? parseEnv(readFileSync(envFile, 'utf8')) : {};
const value = (name) => (process.env[name] ?? local[name] ?? defaults[name]).trim();

// Only these public settings are included in the browser and server bundles.
const environment = {
  apiBaseUrl: value('BACKEND_URL'),
  defaultLocale: value('DEFAULT_LOCALE'),
};

let backendUrl;
try {
  backendUrl = new URL(environment.apiBaseUrl);
} catch {
  throw new Error('BACKEND_URL must be an absolute HTTP or HTTPS URL.');
}
if (!['http:', 'https:'].includes(backendUrl.protocol) || backendUrl.username || backendUrl.password) {
  throw new Error('BACKEND_URL must use HTTP or HTTPS without embedded credentials.');
}
if (!environment.defaultLocale) {
  throw new Error('DEFAULT_LOCALE must not be empty.');
}
try {
  Intl.getCanonicalLocales(environment.defaultLocale);
} catch {
  throw new Error('DEFAULT_LOCALE must be a valid language tag, for example en-CA.');
}

const output = new URL('../src/app/core/app-environment.generated.ts', import.meta.url);
const source = '// Generated by npm run config:generate. Do not edit.\n' +
  `export const appEnvironment = ${JSON.stringify(environment, null, 2)} as const;\n`;
mkdirSync(new URL('.', output), { recursive: true });
if (!existsSync(output) || readFileSync(output, 'utf8') !== source) {
  writeFileSync(output, source);
}
